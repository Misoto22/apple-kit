/** The Swift and CSS that tokens become. Pure functions over Style Dictionary's resolved tokens, tested in test/. */

const HEADER = "Generated by misoto-tokens (apple-kit/tokens) from DTCG tokens; do not edit.";

/** `#RGB`, `#RRGGBB` or `#RRGGBBAA` → `{ hex: 0xRRGGBB, alpha }`. */
export function parseColor(value) {
  const raw = String(value).trim().replace(/^#/, "");
  const full = raw.length === 3 ? [...raw].map((c) => c + c).join("") : raw;
  if (!/^[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/.test(full)) throw new Error(`not a hex colour: ${value}`);
  const hex = full.slice(0, 6).toUpperCase();
  const alpha = full.length === 8 ? Math.round((parseInt(full.slice(6), 16) / 255) * 1000) / 1000 : 1;
  return { hex, alpha };
}

const rgba = (value) => {
  const { hex, alpha } = parseColor(value);
  return alpha === 1 ? `RGBA(hex: 0x${hex})` : `RGBA(hex: 0x${hex}, alpha: ${alpha})`;
};

/** `paper`, `["palette", "ink-strong"]` → `inkStrong` under its group. */
export function swiftName(path) {
  const last = path[path.length - 1];
  const camel = last.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
  const name = camel.charAt(0).toLowerCase() + camel.slice(1);
  return /^[0-9]/.test(name) ? `_${name}` : name;
}

const typeName = (segment) => {
  const camel = segment.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
  return camel.charAt(0).toUpperCase() + camel.slice(1);
};

function swiftValue(token) {
  const type = token.$type ?? token.type;
  const value = token.$value ?? token.value;
  const ext = token.$extensions ?? {};
  if (type === "color") {
    const light = rgba(value);
    const dark = ext["misoto.dark"] ? rgba(ext["misoto.dark"]) : light;
    const parts = [`light: ${light}`, `dark: ${dark}`];
    if (ext["misoto.lightIncreasedContrast"]) parts.push(`lightIncreasedContrast: ${rgba(ext["misoto.lightIncreasedContrast"])}`);
    if (ext["misoto.darkIncreasedContrast"]) parts.push(`darkIncreasedContrast: ${rgba(ext["misoto.darkIncreasedContrast"])}`);
    return { type: "ColorPair", expression: `ColorPair(${parts.join(", ")})` };
  }
  if (type === "duration") {
    const seconds = typeof value === "object" ? (value.unit === "ms" ? value.value / 1000 : value.value) : Number(value);
    return { type: "TimeInterval", expression: String(seconds) };
  }
  if (type === "dimension") {
    const points = typeof value === "object" ? value.value : Number(String(value).replace(/px|pt$/, ""));
    return { type: "CGFloat", expression: String(points) };
  }
  if (type === "number") return { type: "Double", expression: String(value) };
  throw new Error(`${token.path.join(".")}: no Swift form for $type ${type}`);
}

/** One `public enum` per top-level group, nested by path, sorted as the source orders them. */
export function swiftFormat(tokens, enumName) {
  const root = { children: new Map(), tokens: [] };
  for (const token of tokens) {
    let node = root;
    for (const segment of token.path.slice(0, -1)) {
      if (!node.children.has(segment)) node.children.set(segment, { children: new Map(), tokens: [] });
      node = node.children.get(segment);
    }
    node.tokens.push(token);
  }
  const lines = [`// ${HEADER}`, "", "import CoreGraphics", "import Foundation", "import MisotoTheme", ""];
  const emit = (node, name, depth) => {
    const pad = "    ".repeat(depth);
    lines.push(`${pad}public enum ${name} {`);
    for (const token of node.tokens) {
      const { type, expression } = swiftValue(token);
      const description = token.$description ?? token.description;
      if (description) lines.push(`${pad}    /// ${String(description).replace(/\s+/g, " ")}`);
      lines.push(`${pad}    public static let ${swiftName(token.path)}: ${type} = ${expression}`);
    }
    for (const [segment, child] of node.children) emit(child, typeName(segment), depth + 1);
    lines.push(`${pad}}`);
  };
  emit(root, enumName, 0);
  return lines.join("\n") + "\n";
}

/** Light values on `:root`, dark ones under `prefers-color-scheme: dark`. */
export function cssFormat(tokens) {
  const name = (token) => `--${token.path.join("-")}`;
  const light = [];
  const dark = [];
  for (const token of tokens) {
    const type = token.$type ?? token.type;
    const value = token.$value ?? token.value;
    if (type === "color") {
      light.push(`  ${name(token)}: ${value};`);
      const d = token.$extensions?.["misoto.dark"];
      if (d) dark.push(`    ${name(token)}: ${d};`);
    } else if (type === "duration") {
      const v = typeof value === "object" ? `${value.value}${value.unit}` : `${value}s`;
      light.push(`  ${name(token)}: ${v};`);
    } else if (type === "dimension") {
      const v = typeof value === "object" ? `${value.value}${value.unit}` : value;
      light.push(`  ${name(token)}: ${v};`);
    } else {
      light.push(`  ${name(token)}: ${value};`);
    }
  }
  const out = [`/* ${HEADER} */`, ":root {", ...light, "}"];
  if (dark.length) out.push("@media (prefers-color-scheme: dark) {", "  :root {", ...dark, "  }", "}");
  return out.join("\n") + "\n";
}
