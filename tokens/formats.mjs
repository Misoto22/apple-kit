/** The Swift, Kotlin, and CSS that tokens become. Pure functions over Style Dictionary's resolved tokens, tested in test/. */

const HEADER = "Generated by misoto-tokens (apple-kit/tokens) from DTCG tokens; do not edit.";

/** `#RGB`, `#RRGGBB` or `#RRGGBBAA` -> `{ hex: 0xRRGGBB, alpha, aarrggbb }`. */
export function parseColor(value) {
  const raw = String(value).trim().replace(/^#/, "");
  const full = raw.length === 3 ? [...raw].map((c) => c + c).join("") : raw;
  if (!/^[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/.test(full)) throw new Error(`not a hex colour: ${value}`);
  const hex = full.slice(0, 6).toUpperCase();
  const alphaByte = full.length === 8 ? full.slice(6).toUpperCase() : "FF";
  const alpha = full.length === 8 ? Math.round((parseInt(full.slice(6), 16) / 255) * 1000) / 1000 : 1;
  return { hex, alpha, aarrggbb: `${alphaByte}${hex}` };
}

const rgba = (value) => {
  const { hex, alpha } = parseColor(value);
  return alpha === 1 ? `RGBA(hex: 0x${hex})` : `RGBA(hex: 0x${hex}, alpha: ${alpha})`;
};

/** `paper`, `["palette", "ink-strong"]` -> `inkStrong` under its group. */
export function swiftName(path) {
  const last = path[path.length - 1];
  const camel = last.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
  const name = camel.charAt(0).toLowerCase() + camel.slice(1);
  return /^[0-9]/.test(name) ? `_${name}` : name;
}

export function kotlinName(path) {
  const joined = path.join("_");
  const camel = joined.replace(/[-_ ./]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
  const name = camel.charAt(0).toLowerCase() + camel.slice(1);
  return /^[0-9]/.test(name) ? `_${name}` : name;
}

const typeName = (segment) => {
  const camel = segment.replace(/[-_ ]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase());
  return camel.charAt(0).toUpperCase() + camel.slice(1);
};

function parseDurationSeconds(value) {
  return typeof value === "object" ? (value.unit === "ms" ? value.value / 1000 : value.value) : Number(value);
}

function parseDimensionPoints(value) {
  return typeof value === "object" ? value.value : Number(String(value).replace(/px|pt|dp|sp$/, ""));
}

function swiftShadowExpr(s) {
  const x = parseDimensionPoints(s.offsetX ?? s.x ?? 0);
  const y = parseDimensionPoints(s.offsetY ?? s.y ?? 0);
  const blur = parseDimensionPoints(s.blur ?? 0);
  const spread = parseDimensionPoints(s.spread ?? 0);
  const color = rgba(s.color ?? "#000000");
  return `ShadowToken(x: ${x}, y: ${y}, blur: ${blur}, spread: ${spread}, color: ${color})`;
}

function swiftFontWeight(weight) {
  if (typeof weight === "number") {
    if (weight <= 200) return ".ultraLight";
    if (weight <= 300) return ".light";
    if (weight <= 400) return ".regular";
    if (weight <= 500) return ".medium";
    if (weight <= 600) return ".semibold";
    if (weight <= 700) return ".bold";
    if (weight <= 800) return ".heavy";
    return ".black";
  }
  const map = {
    ultralight: ".ultraLight",
    thin: ".thin",
    light: ".light",
    regular: ".regular",
    normal: ".regular",
    medium: ".medium",
    semibold: ".semibold",
    bold: ".bold",
    heavy: ".heavy",
    black: ".black",
  };
  return map[String(weight ?? "regular").toLowerCase()] ?? ".regular";
}

function swiftTextStyle(style) {
  const valid = new Set([
    "largeTitle", "title", "title2", "title3", "headline", "subheadline",
    "body", "callout", "footnote", "caption", "caption2",
  ]);
  return valid.has(style) ? `.${style}` : ".body";
}

function swiftFontDesign(design) {
  const valid = new Set(["default", "serif", "rounded", "monospaced"]);
  return valid.has(design) ? `.${design}` : ".default";
}

function swiftValue(token) {
  const type = token.$type ?? token.type;
  const value = token.$value ?? token.value;
  const ext = token.$extensions ?? {};
  if (type === "color") {
    const light = rgba(value);
    const dark = ext["misoto.dark"] ? rgba(ext["misoto.dark"]) : light;
    const parts = [`light: ${light}`, `dark: ${dark}`];
    if (ext["misoto.lightIncreasedContrast"]) parts.push(`lightIncreasedContrast: ${rgba(ext["misoto.lightIncreasedContrast"])}`);
    if (ext["misoto.darkIncreasedContrast"]) parts.push(`darkIncreasedContrast: ${rgba(ext["misoto.darkIncreasedContrast"])}`);
    return { type: "ColorPair", expression: `ColorPair(${parts.join(", ")})` };
  }
  if (type === "duration") {
    return { type: "TimeInterval", expression: String(parseDurationSeconds(value)) };
  }
  if (type === "dimension") {
    return { type: "CGFloat", expression: String(parseDimensionPoints(value)) };
  }
  if (type === "number") {
    return { type: "Double", expression: String(value) };
  }
  if (type === "cubicBezier") {
    if (!Array.isArray(value) || value.length !== 4) throw new Error(`${token.path.join(".")}: cubicBezier must be 4 numbers`);
    const [x1, y1, x2, y2] = value.map(Number);
    return { type: "CubicBezier", expression: `CubicBezier(x1: ${x1}, y1: ${y1}, x2: ${x2}, y2: ${y2})` };
  }
  if (type === "shadow") {
    if (ext["misoto.dark"]) {
      return {
        type: "ShadowPair",
        expression: `ShadowPair(light: ${swiftShadowExpr(value)}, dark: ${swiftShadowExpr(ext["misoto.dark"])})`,
      };
    }
    return { type: "ShadowToken", expression: swiftShadowExpr(value) };
  }
  if (type === "typography") {
    const textStyle = swiftTextStyle(value.textStyle);
    const weight = swiftFontWeight(value.fontWeight ?? value.weight);
    const family = value.fontFamily;
    if (family && String(family).toLowerCase() !== "system") {
      const size = parseDimensionPoints(value.fontSize ?? 17);
      return {
        type: "FontRole",
        expression: `FontRole.custom(${JSON.stringify(String(family))}, size: ${size}, relativeTo: ${textStyle}, weight: ${weight})`,
      };
    }
    const design = swiftFontDesign(value.design);
    return {
      type: "FontRole",
      expression: `FontRole.system(${textStyle}, design: ${design}, weight: ${weight})`,
    };
  }
  throw new Error(`${token.path.join(".")}: no Swift form for $type ${type}`);
}

/** Validates resolved tokens against the Misoto Theme SSOT schema (`required` + `optional` type checks). */
export function validateThemeTokens(tokens, schema) {
  const byPath = new Map(tokens.map((t) => [t.path.join("."), t]));
  const errors = [];

  for (const [path, expectedType] of Object.entries(schema.required ?? {})) {
    const token = byPath.get(path);
    if (!token) {
      errors.push(`missing required token '${path}' ($type '${expectedType}')`);
      continue;
    }
    const actualType = token.$type ?? token.type;
    if (actualType !== expectedType) {
      errors.push(`token '${path}' expected $type '${expectedType}' but got '${actualType}'`);
    }
  }

  for (const [path, expectedType] of Object.entries(schema.optional ?? {})) {
    const token = byPath.get(path);
    if (!token) continue;
    const actualType = token.$type ?? token.type;
    if (actualType !== expectedType) {
      errors.push(`token '${path}' expected $type '${expectedType}' but got '${actualType}'`);
    }
  }

  if (errors.length) {
    throw new Error(`Theme schema validation failed:\n- ${errors.join("\n- ")}`);
  }
  return byPath;
}

/** One `public enum` per top-level group, nested by path, sorted as the source orders them. */
export function swiftFormat(tokens, enumName) {
  const root = { children: new Map(), tokens: [] };
  let usesMotion = false;
  for (const token of tokens) {
    const type = token.$type ?? token.type;
    if (type === "cubicBezier") usesMotion = true;
    let node = root;
    for (const segment of token.path.slice(0, -1)) {
      if (!node.children.has(segment)) node.children.set(segment, { children: new Map(), tokens: [] });
      node = node.children.get(segment);
    }
    node.tokens.push(token);
  }
  const imports = ["import CoreGraphics", "import Foundation"];
  if (usesMotion) imports.push("import MisotoMotion");
  imports.push("import MisotoTheme", "import SwiftUI");
  const lines = [`// ${HEADER}`, "", ...imports, ""];
  const emit = (node, name, depth) => {
    const pad = "    ".repeat(depth);
    lines.push(`${pad}public enum ${name} {`);
    for (const token of node.tokens) {
      const { type, expression } = swiftValue(token);
      const description = token.$description ?? token.description;
      if (description) lines.push(`${pad}    /// ${String(description).replace(/\s+/g, " ")}`);
      lines.push(`${pad}    public static let ${swiftName(token.path)}: ${type} = ${expression}`);
    }
    for (const [segment, child] of node.children) emit(child, typeName(segment), depth + 1);
    lines.push(`${pad}}`);
  };
  emit(root, enumName, 0);
  return lines.join("\n") + "\n";
}

/** Validates against `schema`, emits the token enum, and appends `extension Theme { public static let <themePropertyName> = ... }`. */
export function swiftThemeFormat(tokens, enumName, themePropertyName, schema) {
  const byPath = validateThemeTokens(tokens, schema);
  const base = swiftFormat(tokens, enumName);
  const ref = (dotPath) => {
    const parts = dotPath.split(".");
    const prefix = parts.slice(0, -1).map(typeName).join(".");
    const leaf = swiftName(parts);
    return `${enumName}.${prefix}.${leaf}`;
  };
  const shadowExpr = (dotPath) => {
    const token = byPath.get(dotPath);
    if (!token) return "nil";
    const ext = token.$extensions ?? {};
    return ext["misoto.dark"] ? ref(dotPath) : `ShadowPair(${ref(dotPath)})`;
  };

  const extLines = [
    "",
    "extension Theme {",
    `    /// Generated from DTCG tokens via misoto-tokens SSOT schema.`,
    `    public static let ${themePropertyName} = Theme(`,
    "        colors: Theme.Colors(",
    `            paper: Color(${ref("color.paper")}),`,
    `            surface: Color(${ref("color.surface")}),`,
    `            ink: Color(${ref("color.ink")}),`,
    `            secondaryInk: Color(${ref("color.secondaryInk")}),`,
    `            tertiaryInk: Color(${ref("color.tertiaryInk")}),`,
    `            hairline: Color(${ref("color.hairline")}),`,
    `            scrim: Color(${ref("color.scrim")}),`,
    `            accent: Color(${ref("color.accent")}),`,
    `            onAccent: Color(${ref("color.onAccent")}),`,
    `            skeleton: Color(${ref("color.skeleton")}),`,
    `            success: Color(${ref("color.success")}),`,
    `            warning: Color(${ref("color.warning")}),`,
    `            error: Color(${ref("color.error")}),`,
    "            glass: Theme.Colors.Glass(",
    `                secondaryInk: Color(${ref("color.glass.secondaryInk")}),`,
    `                tertiaryInk: Color(${ref("color.glass.tertiaryInk")}),`,
    `                wash: Color(${ref("color.glass.wash")}),`,
    `                band: Color(${ref("color.glass.band")})`,
    "            )",
    "        ),",
    "        typography: Theme.Typography(",
    `            title: ${ref("typography.title")},`,
    `            headline: ${ref("typography.headline")},`,
    `            body: ${ref("typography.body")},`,
    `            callout: ${ref("typography.callout")},`,
    `            caption: ${ref("typography.caption")},`,
    `            mono: ${ref("typography.mono")}`,
    "        ),",
    "        radii: Theme.Radii(",
    `            small: ${ref("radii.small")},`,
    `            medium: ${ref("radii.medium")},`,
    `            large: ${ref("radii.large")},`,
    `            control: ${ref("radii.control")},`,
    `            card: ${ref("radii.card")}`,
    "        ),",
    "        spacing: Theme.Spacing(",
    `            xs: ${ref("spacing.xs")},`,
    `            sm: ${ref("spacing.sm")},`,
    `            md: ${ref("spacing.md")},`,
    `            lg: ${ref("spacing.lg")},`,
    `            xl: ${ref("spacing.xl")}`,
    "        ),",
    "        elevation: Theme.Elevation(",
    `            card: ${shadowExpr("elevation.card")},`,
    `            floating: ${shadowExpr("elevation.floating")},`,
    `            strokeWidth: ${ref("elevation.strokeWidth")}`,
    "        )",
    "    )",
    "}",
  ];
  return base + extLines.join("\n") + "\n";
}

function cssShadow(s) {
  const x = parseDimensionPoints(s.offsetX ?? s.x ?? 0);
  const y = parseDimensionPoints(s.offsetY ?? s.y ?? 0);
  const blur = parseDimensionPoints(s.blur ?? 0);
  const spread = parseDimensionPoints(s.spread ?? 0);
  return `${x}px ${y}px ${blur}px ${spread}px ${s.color ?? "#000000"}`;
}

/** Light values on `:root`, dark under `prefers-color-scheme: dark`, high contrast under `prefers-contrast: more`. */
export function cssFormat(tokens) {
  const name = (token) => `--${token.path.join("-")}`;
  const light = [];
  const dark = [];
  const lightHighContrast = [];
  const darkHighContrast = [];
  for (const token of tokens) {
    const type = token.$type ?? token.type;
    const value = token.$value ?? token.value;
    const ext = token.$extensions ?? {};
    if (type === "color") {
      light.push(`  ${name(token)}: ${value};`);
      if (ext["misoto.dark"]) dark.push(`    ${name(token)}: ${ext["misoto.dark"]};`);
      if (ext["misoto.lightIncreasedContrast"]) lightHighContrast.push(`    ${name(token)}: ${ext["misoto.lightIncreasedContrast"]};`);
      if (ext["misoto.darkIncreasedContrast"]) darkHighContrast.push(`      ${name(token)}: ${ext["misoto.darkIncreasedContrast"]};`);
    } else if (type === "duration") {
      const v = typeof value === "object" ? `${value.value}${value.unit}` : `${value}s`;
      light.push(`  ${name(token)}: ${v};`);
    } else if (type === "dimension") {
      const v = typeof value === "object" ? `${value.value}${value.unit}` : value;
      light.push(`  ${name(token)}: ${v};`);
    } else if (type === "cubicBezier") {
      if (!Array.isArray(value) || value.length !== 4) throw new Error(`${token.path.join(".")}: cubicBezier must be 4 numbers`);
      light.push(`  ${name(token)}: cubic-bezier(${value.join(", ")});`);
    } else if (type === "shadow") {
      light.push(`  ${name(token)}: ${cssShadow(value)};`);
      if (ext["misoto.dark"]) dark.push(`    ${name(token)}: ${cssShadow(ext["misoto.dark"])};`);
    } else if (type === "typography") {
      if (value.fontFamily) light.push(`  ${name(token)}-family: ${value.fontFamily};`);
      if (value.fontSize !== undefined) {
        const size = typeof value.fontSize === "object" ? `${value.fontSize.value}${value.fontSize.unit}` : `${value.fontSize}px`;
        light.push(`  ${name(token)}-size: ${size};`);
      }
      if (value.fontWeight !== undefined || value.weight !== undefined) {
        light.push(`  ${name(token)}-weight: ${value.fontWeight ?? value.weight};`);
      }
    } else {
      light.push(`  ${name(token)}: ${value};`);
    }
  }
  const out = [`/* ${HEADER} */`, ":root {", ...light, "}"];
  if (dark.length) out.push("@media (prefers-color-scheme: dark) {", "  :root {", ...dark, "  }", "}");
  if (lightHighContrast.length || darkHighContrast.length) {
    out.push("@media (prefers-contrast: more) {");
    if (lightHighContrast.length) out.push("  :root {", ...lightHighContrast, "  }");
    if (darkHighContrast.length) {
      out.push("  @media (prefers-color-scheme: dark) {", "    :root {", ...darkHighContrast, "    }", "  }");
    }
    out.push("}");
  }
  return out.join("\n") + "\n";
}

/** Pure-JVM Kotlin primitives matching RevalaTokens.kt (zero Android/Compose imports). */
export function kotlinFormat(tokens, objectName = "BrandTokens", packageName = "") {
  const colorTokens = [];
  const otherTokens = [];
  for (const token of tokens) {
    const type = token.$type ?? token.type;
    if (type === "color") colorTokens.push(token);
    else otherTokens.push(token);
  }

  const lines = [
    `// ${HEADER}`,
    "// Primitives only, with no Android or Compose import, so it compiles in a pure-JVM module.",
    `@file:Suppress("ConstPropertyName", "ktlint:standard:property-naming")`,
    "",
  ];
  if (packageName) lines.push(`package ${packageName}`, "");

  lines.push(`object ${objectName} {`);

  if (colorTokens.length) {
    const modes = [
      ["Light", (t) => t.$value ?? t.value],
      ["Dark", (t) => (t.$extensions ?? {})["misoto.dark"] ?? (t.$value ?? t.value)],
      ["LightHighContrast", (t) => (t.$extensions ?? {})["misoto.lightIncreasedContrast"] ?? (t.$value ?? t.value)],
      ["DarkHighContrast", (t) => (t.$extensions ?? {})["misoto.darkIncreasedContrast"] ?? (t.$extensions ?? {})["misoto.dark"] ?? (t.$value ?? t.value)],
    ];
    for (const [modeName, pick] of modes) {
      lines.push(`    object ${modeName} {`);
      for (const token of colorTokens) {
        const { aarrggbb } = parseColor(pick(token));
        lines.push(`        const val ${kotlinName(token.path)}: Long = 0x${aarrggbb}`);
      }
      lines.push("    }");
    }
  }

  if (otherTokens.length) {
    lines.push("    object Values {");
    for (const token of otherTokens) {
      const type = token.$type ?? token.type;
      const value = token.$value ?? token.value;
      const prop = kotlinName(token.path);
      if (type === "duration") {
        const ms = Math.round(parseDurationSeconds(value) * 1000);
        lines.push(`        const val ${prop}Ms: Long = ${ms}L`);
      } else if (type === "dimension") {
        const pts = parseDimensionPoints(value);
        lines.push(`        const val ${prop}: Float = ${pts}f`);
      } else if (type === "number") {
        lines.push(`        const val ${prop}: Double = ${Number(value)}`);
      } else if (type === "cubicBezier") {
        if (!Array.isArray(value) || value.length !== 4) throw new Error(`${token.path.join(".")}: cubicBezier must be 4 numbers`);
        const [x1, y1, x2, y2] = value.map(Number);
        lines.push(`        val ${prop}: FloatArray = floatArrayOf(${x1}f, ${y1}f, ${x2}f, ${y2}f)`);
      } else if (type === "shadow") {
        const x = parseDimensionPoints(value.offsetX ?? value.x ?? 0);
        const y = parseDimensionPoints(value.offsetY ?? value.y ?? 0);
        const blur = parseDimensionPoints(value.blur ?? 0);
        const spread = parseDimensionPoints(value.spread ?? 0);
        const { aarrggbb } = parseColor(value.color ?? "#000000");
        lines.push(`        const val ${prop}X: Float = ${x}f`);
        lines.push(`        const val ${prop}Y: Float = ${y}f`);
        lines.push(`        const val ${prop}Blur: Float = ${blur}f`);
        lines.push(`        const val ${prop}Spread: Float = ${spread}f`);
        lines.push(`        const val ${prop}Color: Long = 0x${aarrggbb}`);
      } else if (type === "typography") {
        if (value.fontFamily) lines.push(`        const val ${prop}Family: String = ${JSON.stringify(String(value.fontFamily))}`);
        if (value.fontSize !== undefined) lines.push(`        const val ${prop}SizeSp: Float = ${parseDimensionPoints(value.fontSize)}f`);
        if (value.fontWeight !== undefined || value.weight !== undefined) {
          lines.push(`        const val ${prop}Weight: String = ${JSON.stringify(String(value.fontWeight ?? value.weight))}`);
        }
      } else {
        throw new Error(`${token.path.join(".")}: no Kotlin form for $type ${type}`);
      }
    }
    lines.push("    }");
  }

  lines.push("}");
  return lines.join("\n") + "\n";
}
